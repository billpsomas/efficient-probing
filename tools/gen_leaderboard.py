#!/usr/bin/env python3
"""Regenerate the README leaderboard from results.csv.

results.csv is the single source of truth. Adding a model means adding one line
there and re-running this script; the three README views are derived, never
hand-edited.

    python tools/gen_leaderboard.py           # rewrite README.md in place
    python tools/gen_leaderboard.py --check   # exit 1 if README is stale (for CI)
    python tools/gen_leaderboard.py --stdout  # print the block, touch nothing

CSV columns
    family      MIM | JEA | Hybrid | VLM | GEN
    method      MAE, DINOv3, SigLIP2, ...
    arch        ViT-L/16, RN-50, DiT-XL/2, ...
    pretrain    pre-training dataset
    eval        evaluation dataset
    image_size  evaluation resolution in pixels
    lp          linear-probing top-1
    lp_gap      yes if LP used GAP instead of [CLS] (renders the marker)
    ep          efficient-probing top-1
    ep_queries  winning --ep_queries for the EP number (blank if unknown)
    ep_variant  'ep' or 'ep_all' — which one the EP number came from (blank if unknown)
    model       exact --model string
    loader      openclip | timm | radio | simmim | dinov3 | hub | "" (default models_vit)
                or "unsupported:<name>" when this repo has no loader for it yet
    pretrain_tag  --openclip_pretrain value, for openclip rows
    finetune    --finetune value (timm tag or checkpoint path)
    lp_variant  cls | pos — which one produced the LP number
    lp_log      repo-relative path to the LP training log (blank if not published)
    ep_log      repo-relative path to the EP training log (blank if not published)
    notes       free text; non-empty rows are listed under Provenance
    ep_head     peak | final | blank -- whether the released EP head on HF is the
                run's best epoch (reproduces the table number) or its final epoch

A row is REPRODUCIBLE only when model, loader, ep_queries, ep_variant and
lp_variant are all recorded. Anything else is reported as unverified rather
than guessed.
"""
